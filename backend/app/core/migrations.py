async def upgrade(connection: AsyncConnection) -> None:
    await connection.execute(
        text("SELECT pg_advisory_xact_lock(:lock_id)"),
        {"lock_id": MIGRATION_ADVISORY_LOCK},
    )
    await connection.execute(text(
        "CREATE TABLE IF NOT EXISTS schema_migrations "
        "(revision VARCHAR(100) PRIMARY KEY, applied_at TIMESTAMPTZ NOT NULL DEFAULT now())"
    ))
    applied = set((await connection.execute(text("SELECT revision FROM schema_migrations"))).scalars())
    for revision, statements in MIGRATIONS.items():
        if revision in applied:
            continue
        for statement in statements:
            await connection.execute(text(statement))
        await connection.execute(
            text("INSERT INTO schema_migrations (revision) VALUES (:revision)"),
            {"revision": revision},
        )


async def downgrade(connection: AsyncConnection, target: str = "base") -> None:
    if target != "base" and target not in MIGRATIONS:
        raise ValueError(f"Unknown migration target: {target}")
    await connection.execute(
        text("SELECT pg_advisory_xact_lock(:lock_id)"),
        {"lock_id": MIGRATION_ADVISORY_LOCK},
    )
    await connection.execute(text(
        "CREATE TABLE IF NOT EXISTS schema_migrations "
        "(revision VARCHAR(100) PRIMARY KEY, applied_at TIMESTAMPTZ NOT NULL DEFAULT now())"
    ))
    applied = set((await connection.execute(text("SELECT revision FROM schema_migrations"))).scalars())
    for revision in reversed(tuple(MIGRATIONS)):
        if revision == target:
            break
        if revision not in applied:
            continue
        for statement in DOWN_MIGRATIONS[revision]:
            await connection.execute(text(statement))
        await connection.execute(
            text("DELETE FROM schema_migrations WHERE revision = :revision"),
            {"revision": revision},
        )


async def _main() -> None:
    from app.core.database import engine

    parser = argparse.ArgumentParser(description="Manage PostgreSQL schema migrations")
    parser.add_argument("action", choices=("upgrade", "downgrade"))
    parser.add_argument("target", nargs="?", default="base")
    args = parser.parse_args()
    async with engine.begin() as connection:
        if args.action == "upgrade":
            await upgrade(connection)
        else:
            await downgrade(connection, args.target)
    await engine.dispose()


if __name__ == "__main__":
    import asyncio

    asyncio.run(_main())